-- ---------- Audit trigger that works for tables without an "id" column ----------
create or replace function public.write_audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  rec jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  insert into public.audit_log (table_name, row_id, action, old_data, new_data, changed_by)
  values (
    tg_table_name,
    coalesce((rec ->> 'id')::bigint, (rec ->> 'school_id')::bigint),
    tg_op,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end,
    public.current_email()
  );
  return null;
end $$;

-- ---------- Follow-ups: mark as done ----------
alter table public.interactions add column if not exists follow_up_done    boolean not null default false;
alter table public.interactions add column if not exists follow_up_done_at timestamptz;
alter table public.interactions add column if not exists follow_up_done_by text;

create index if not exists interactions_open_follow_ups_idx
  on public.interactions (next_follow_up) where next_follow_up is not null and not follow_up_done;

-- Any team member may close any follow-up (row edits stay limited to the author/admin)
create or replace function public.complete_follow_up(p_id bigint, p_done boolean default true) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_team_member() then
    raise exception 'not allowed';
  end if;
  update public.interactions
     set follow_up_done    = p_done,
         follow_up_done_at = case when p_done then now() end,
         follow_up_done_by = case when p_done then public.current_email() end
   where id = p_id and next_follow_up is not null;
end $$;

revoke all on function public.complete_follow_up(bigint, boolean) from public, anon;
grant execute on function public.complete_follow_up(bigint, boolean) to authenticated;

-- ---------- Campaigns ----------
create table if not exists public.campaigns (
  id          bigint generated by default as identity primary key,
  name        text not null,
  channel     text not null default 'whatsapp' check (channel in ('whatsapp', 'email', 'mixed')),
  subject     text,
  body        text,
  archived    boolean not null default false,
  created_at  timestamptz not null default now(),
  created_by  text not null default public.current_email()
);

create table if not exists public.campaign_targets (
  campaign_id  bigint not null references public.campaigns(id) on delete cascade,
  school_id    bigint not null references public.schools(id) on delete cascade,
  status       text not null default 'pending'
               check (status in ('pending', 'sent', 'replied', 'interested', 'not_interested')),
  sent_at      timestamptz,
  replied_at   timestamptz,
  updated_at   timestamptz not null default now(),
  updated_by   text not null default public.current_email(),
  primary key (campaign_id, school_id)
);
create index if not exists campaign_targets_school_idx on public.campaign_targets (school_id);

create or replace function public.touch_campaign_target() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := public.current_email();
  if new.status <> 'pending' and new.sent_at is null then
    new.sent_at := now();
  end if;
  if new.status in ('replied', 'interested', 'not_interested') and new.replied_at is null then
    new.replied_at := now();
  end if;
  if new.status = 'pending' then
    new.sent_at := null;
    new.replied_at := null;
  end if;
  return new;
end $$;

drop trigger if exists campaign_targets_touch on public.campaign_targets;
create trigger campaign_targets_touch before insert or update on public.campaign_targets
for each row execute function public.touch_campaign_target();

drop trigger if exists campaigns_audit on public.campaigns;
create trigger campaigns_audit after insert or update or delete on public.campaigns
for each row execute function public.write_audit();

drop trigger if exists campaign_targets_audit on public.campaign_targets;
create trigger campaign_targets_audit after update or delete on public.campaign_targets
for each row execute function public.write_audit();

alter table public.campaigns        enable row level security;
alter table public.campaign_targets enable row level security;

drop policy if exists campaigns_read   on public.campaigns;
drop policy if exists campaigns_insert on public.campaigns;
drop policy if exists campaigns_update on public.campaigns;
drop policy if exists campaigns_delete on public.campaigns;
create policy campaigns_read   on public.campaigns for select to authenticated using (public.is_team_member());
create policy campaigns_insert on public.campaigns for insert to authenticated
  with check (public.is_team_member() and created_by = public.current_email());
create policy campaigns_update on public.campaigns for update to authenticated
  using (public.is_team_member()) with check (public.is_team_member());
create policy campaigns_delete on public.campaigns for delete to authenticated
  using (public.is_admin() or created_by = public.current_email());

drop policy if exists targets_read   on public.campaign_targets;
drop policy if exists targets_insert on public.campaign_targets;
drop policy if exists targets_update on public.campaign_targets;
drop policy if exists targets_delete on public.campaign_targets;
create policy targets_read   on public.campaign_targets for select to authenticated using (public.is_team_member());
create policy targets_insert on public.campaign_targets for insert to authenticated with check (public.is_team_member());
create policy targets_update on public.campaign_targets for update to authenticated
  using (public.is_team_member()) with check (public.is_team_member());
create policy targets_delete on public.campaign_targets for delete to authenticated using (public.is_team_member());
