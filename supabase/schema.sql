-- ---------- Team members (who is allowed to use the CRM) ----------
create table if not exists public.team_members (
  email       text primary key check (email = lower(email)),
  full_name   text,
  role        text not null default 'marketer' check (role in ('admin', 'marketer')),
  created_at  timestamptz not null default now()
);

create or replace function public.current_email() returns text
language sql stable as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;

create or replace function public.is_team_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.team_members where email = public.current_email())
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.team_members where email = public.current_email() and role = 'admin')
$$;

-- ---------- Schools / customers ----------
create table if not exists public.schools (
  id          bigint generated by default as identity primary key,
  name        text not null,
  zone        text,
  category    text,
  address     text,
  phones      text[] not null default '{}',
  whatsapp    text,
  email       text,
  links       jsonb not null default '[]'::jsonb,
  stages      text,
  status      text not null default 'لم يتم التواصل'
              check (status in ('لم يتم التواصل', 'تم إرسال عرض', 'مهتم / متابعة', 'تم التعاقد', 'غير مهتم')),
  notes       text,
  created_at  timestamptz not null default now(),
  created_by  text not null default public.current_email(),
  updated_at  timestamptz not null default now(),
  updated_by  text not null default public.current_email()
);

-- ---------- Interactions: notes, calls, WhatsApp, emails, visits, status changes ----------
create table if not exists public.interactions (
  id              bigint generated by default as identity primary key,
  school_id       bigint not null references public.schools(id) on delete cascade,
  type            text not null default 'note'
                  check (type in ('note', 'call', 'whatsapp', 'email', 'visit', 'meeting', 'status_change', 'other')),
  direction       text check (direction in ('out', 'in')),
  summary         text not null,
  outcome         text,
  next_follow_up  date,
  created_at      timestamptz not null default now(),
  created_by      text not null default public.current_email()
);
create index if not exists interactions_school_idx on public.interactions (school_id, created_at desc);
create index if not exists interactions_follow_up_idx on public.interactions (next_follow_up) where next_follow_up is not null;

-- ---------- Audit log: every change with before/after values ----------
create table if not exists public.audit_log (
  id          bigint generated always as identity primary key,
  table_name  text not null,
  row_id      bigint,
  action      text not null,
  old_data    jsonb,
  new_data    jsonb,
  changed_by  text not null default public.current_email(),
  changed_at  timestamptz not null default now()
);
create index if not exists audit_log_row_idx on public.audit_log (table_name, row_id, changed_at desc);

-- ---------- Triggers ----------
create or replace function public.touch_school() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := public.current_email();
  return new;
end $$;

drop trigger if exists schools_touch on public.schools;
create trigger schools_touch before update on public.schools
for each row execute function public.touch_school();

-- Every status change becomes an entry in the school's timeline
create or replace function public.log_status_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status is distinct from old.status then
    insert into public.interactions (school_id, type, summary, created_by)
    values (new.id, 'status_change', coalesce(old.status, '—') || ' ← ' || new.status, public.current_email());
  end if;
  return new;
end $$;

drop trigger if exists schools_status_log on public.schools;
create trigger schools_status_log after update of status on public.schools
for each row execute function public.log_status_change();

create or replace function public.write_audit() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit_log (table_name, row_id, action, old_data, new_data, changed_by)
  values (
    tg_table_name,
    coalesce((case when tg_op = 'DELETE' then old.id else new.id end), null),
    tg_op,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end,
    public.current_email()
  );
  return null;
end $$;

drop trigger if exists schools_audit on public.schools;
create trigger schools_audit after insert or update or delete on public.schools
for each row execute function public.write_audit();

drop trigger if exists interactions_audit on public.interactions;
create trigger interactions_audit after insert or update or delete on public.interactions
for each row execute function public.write_audit();

-- ---------- Row Level Security: only team members can see or change data ----------
alter table public.team_members enable row level security;
alter table public.schools      enable row level security;
alter table public.interactions enable row level security;
alter table public.audit_log    enable row level security;

drop policy if exists team_read  on public.team_members;
drop policy if exists team_admin on public.team_members;
create policy team_read  on public.team_members for select to authenticated using (public.is_team_member());
create policy team_admin on public.team_members for all    to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists schools_read   on public.schools;
drop policy if exists schools_insert on public.schools;
drop policy if exists schools_update on public.schools;
drop policy if exists schools_delete on public.schools;
create policy schools_read   on public.schools for select to authenticated using (public.is_team_member());
create policy schools_insert on public.schools for insert to authenticated with check (public.is_team_member());
create policy schools_update on public.schools for update to authenticated using (public.is_team_member()) with check (public.is_team_member());
create policy schools_delete on public.schools for delete to authenticated using (public.is_admin());

drop policy if exists interactions_read   on public.interactions;
drop policy if exists interactions_insert on public.interactions;
drop policy if exists interactions_update on public.interactions;
drop policy if exists interactions_delete on public.interactions;
create policy interactions_read   on public.interactions for select to authenticated using (public.is_team_member());
create policy interactions_insert on public.interactions for insert to authenticated
  with check (public.is_team_member() and created_by = public.current_email());
-- Members can edit/delete only their own entries; admins can edit/delete any
create policy interactions_update on public.interactions for update to authenticated
  using (public.is_admin() or created_by = public.current_email())
  with check (public.is_admin() or created_by = public.current_email());
create policy interactions_delete on public.interactions for delete to authenticated
  using (public.is_admin() or created_by = public.current_email());

drop policy if exists audit_read on public.audit_log;
create policy audit_read on public.audit_log for select to authenticated using (public.is_admin());
-- No insert/update/delete policies on audit_log: only the triggers write to it.

